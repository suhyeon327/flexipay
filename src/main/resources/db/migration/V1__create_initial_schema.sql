
-- 1. 상품
CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          sku VARCHAR(50) NOT NULL UNIQUE,
                          name VARCHAR(100) NOT NULL,
                          unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
                          is_discounted BOOLEAN NOT NULL,
                          gift_certificate_eligible BOOLEAN NOT NULL,
                          is_active BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 장바구니
CREATE TABLE carts (
                       id UUID PRIMARY KEY,
                       status VARCHAR(20) NOT NULL
                           CHECK (status IN ('ACTIVE', 'CONVERTED', 'ABANDONED')),
                       version BIGINT NOT NULL DEFAULT 0,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. 장바구니 상품
CREATE TABLE cart_items (
                            id UUID PRIMARY KEY,
                            cart_id UUID NOT NULL REFERENCES carts(id),
                            product_id BIGINT NOT NULL REFERENCES products(id),
                            product_name VARCHAR(100) NOT NULL,
                            unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
                            quantity INTEGER NOT NULL CHECK (quantity > 0),
                            is_discounted BOOLEAN NOT NULL,
                            gift_certificate_eligible BOOLEAN NOT NULL,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id)
);

CREATE INDEX idx_cart_items_cart_id ON cart_items(cart_id);

-- 4. 결제 세션
CREATE TABLE checkout_sessions (
                                   id UUID PRIMARY KEY,
                                   cart_id UUID NOT NULL UNIQUE REFERENCES carts(id),
                                   status VARCHAR(20) NOT NULL
                                       CHECK (status IN ('OPEN', 'LOCKED')),
                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                   updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. 결제 입력 정보
CREATE TABLE checkout_inputs (
                                 id UUID PRIMARY KEY,
                                 checkout_session_id UUID NOT NULL
                                     REFERENCES checkout_sessions(id),
                                 input_type VARCHAR(30) NOT NULL
                                     CHECK (input_type IN (
                                                           'GIFT_CERTIFICATE',
                                                           'TELECOM_DISCOUNT',
                                                           'POINTS'
                                         )),
                                 input_value VARCHAR(200),
                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 CONSTRAINT uk_checkout_inputs_session_type
                                     UNIQUE (checkout_session_id, input_type)
);

CREATE INDEX idx_checkout_inputs_session_id
    ON checkout_inputs(checkout_session_id);